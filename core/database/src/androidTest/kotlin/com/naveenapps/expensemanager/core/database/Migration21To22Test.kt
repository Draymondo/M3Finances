package com.naveenapps.expensemanager.core.database

import androidx.room.testing.MigrationTestHelper
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.google.common.truth.Truth.assertThat
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import java.io.IOException

private const val INSTALLMENT_PLAN_MIGRATION_TEST_DB = "migration_21_22_test"

/** Columns the exported v22 schema declares for `installment_plan`, in order. */
private val EXPECTED_INSTALLMENT_PLAN_COLUMNS = listOf(
    "id",
    "account_id",
    "name",
    "target_amount",
    "deadline",
    "notes",
    "is_completed",
    "created_on",
    "updated_on",
)

/** Tables that already existed at version 21 and must survive the migration untouched. */
private val V21_TABLES = listOf(
    "account",
    "budget",
    "budget_account_relation",
    "budget_category_relation",
    "category",
    "debt",
    "debt_reminder",
    "envelope",
    "pending_notification_processing",
    "pending_transaction",
    "recurring_transaction",
    "savings_goal",
    "shopping_list",
    "shopping_list_item",
    "transaction",
    "transaction_split_item",
)

/**
 * Proves that `MIGRATION_21_22` really works on a populated v21 database.
 *
 * The migration is additive (it only creates the `installment_plan` table), so this test
 * asserts that nothing existing is lost and that the new table matches the exported schema
 * exactly - which `runMigrationsAndValidate(..., validate = true)` enforces, including
 * affinities.
 *
 * NOTE: `runMigrationsAndValidate` also requires the v22 schema JSON (generated by a Room
 * build into `core/database/schemas/.../22.json`) to be present.
 */
@RunWith(AndroidJUnit4::class)
class Migration21To22Test {

    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        ExpenseManagerDatabase::class.java,
    )

    @Test
    @Throws(IOException::class)
    fun preservesExistingDataAndCreatesTheInstallmentPlanTable() {
        seedV21Database()

        // `validate = true` makes Room compare the migrated schema against 22.json: a wrong
        // affinity (e.g. TEXT instead of REAL for the amount) fails right here.
        val db = helper.runMigrationsAndValidate(
            INSTALLMENT_PLAN_MIGRATION_TEST_DB,
            22,
            true,
            MIGRATION_21_22,
        )

        // 1. Every v21 table is still present, plus the new one.
        db.query("SELECT name FROM sqlite_master WHERE type = 'table'").use { cursor ->
            val tables = buildSet { while (cursor.moveToNext()) add(cursor.getString(0)) }
            V21_TABLES.forEach { table -> assertThat(tables).contains(table) }
            assertThat(tables).contains("installment_plan")
        }

        // 2. Pre-existing data survives.
        db.query("SELECT `name`, `amount` FROM `account` WHERE `id` = 'acc-1'").use { cursor ->
            assertThat(cursor.moveToFirst()).isTrue()
            assertThat(cursor.getString(0)).isEqualTo("Wave")
            assertThat(cursor.getDouble(1)).isEqualTo(27744.0)
        }
        db.query("SELECT `name` FROM `savings_goal` WHERE `id` = 'goal-1'").use { cursor ->
            assertThat(cursor.moveToFirst()).isTrue()
            assertThat(cursor.getString(0)).isEqualTo("Vacances")
        }

        // 3. The new table has the expected columns, affinities, nullability and primary key.
        db.query("PRAGMA table_info(installment_plan)").use { cursor ->
            val columns = mutableListOf<String>()
            val affinities = mutableMapOf<String, String>()
            val notNullColumns = mutableListOf<String>()
            val primaryKeys = mutableListOf<String>()
            while (cursor.moveToNext()) {
                val name = cursor.getString(cursor.getColumnIndexOrThrow("name"))
                columns += name
                affinities[name] = cursor.getString(cursor.getColumnIndexOrThrow("type"))
                if (cursor.getInt(cursor.getColumnIndexOrThrow("notnull")) == 1) notNullColumns += name
                if (cursor.getInt(cursor.getColumnIndexOrThrow("pk")) > 0) primaryKeys += name
            }

            assertThat(columns).containsExactlyElementsIn(EXPECTED_INSTALLMENT_PLAN_COLUMNS).inOrder()
            assertThat(affinities["id"]).isEqualTo("TEXT")
            assertThat(affinities["account_id"]).isEqualTo("TEXT")
            assertThat(affinities["name"]).isEqualTo("TEXT")
            assertThat(affinities["target_amount"]).isEqualTo("REAL")
            assertThat(affinities["deadline"]).isEqualTo("INTEGER")
            assertThat(affinities["notes"]).isEqualTo("TEXT")
            assertThat(affinities["is_completed"]).isEqualTo("INTEGER")
            assertThat(affinities["created_on"]).isEqualTo("INTEGER")
            assertThat(affinities["updated_on"]).isEqualTo("INTEGER")
            // Only `deadline` is nullable.
            assertThat(notNullColumns).containsExactly(
                "id", "account_id", "name", "target_amount",
                "notes", "is_completed", "created_on", "updated_on",
            )
            assertThat(primaryKeys).containsExactly("id")
        }

        // 4. The foreign key targets `account(id)` with ON DELETE CASCADE, so deleting the
        // hidden account removes the plan row with it.
        db.query("PRAGMA foreign_key_list(installment_plan)").use { cursor ->
            assertThat(cursor.moveToFirst()).isTrue()
            assertThat(cursor.getString(cursor.getColumnIndexOrThrow("table"))).isEqualTo("account")
            assertThat(cursor.getString(cursor.getColumnIndexOrThrow("on_delete"))).isEqualTo("CASCADE")
        }

        // 5. Starts empty, accepts a row, rejects a dangling account_id.
        db.query("SELECT COUNT(*) FROM `installment_plan`").use { cursor ->
            assertThat(cursor.moveToFirst()).isTrue()
            assertThat(cursor.getInt(0)).isEqualTo(0)
        }

        val insert = "INSERT INTO `installment_plan` (" +
            "`id`, `account_id`, `name`, `target_amount`, `deadline`, `notes`, " +
            "`is_completed`, `created_on`, `updated_on`" +
            ") VALUES (" +
            "'plan-1', 'acc-hidden', 'Téléphone', 300000.0, 1780000000000, '', " +
            "0, 1710000000000, 1710000000000)"
        // FK references account(id): the hidden account doesn't exist yet -> must fail.
        db.execSQL("PRAGMA foreign_keys=ON")
        assertThat(runCatching { db.execSQL(insert) }.isFailure).isTrue()

        db.execSQL(
            "INSERT INTO `account` (" +
                "`id`, `name`, `type`, `icon_background_color`, `icon_name`, `amount`, " +
                "`credit_limit`, `sequence`, `created_on`, `updated_on`" +
                ") VALUES (" +
                "'acc-hidden', 'Téléphone', 6, '#FF6D00', 'ic_wallet', 0.0, " +
                "0.0, 0, 1710000000000, 1710000000000)",
        )
        db.execSQL(insert)

        db.query("SELECT `name`, `target_amount` FROM `installment_plan`").use { cursor ->
            assertThat(cursor.moveToFirst()).isTrue()
            assertThat(cursor.getString(0)).isEqualTo("Téléphone")
            assertThat(cursor.getDouble(1)).isEqualTo(300000.0)
        }

        db.close()
    }

    private fun seedV21Database() {
        helper.createDatabase(INSTALLMENT_PLAN_MIGRATION_TEST_DB, 21).apply {
            execSQL(
                "INSERT INTO `account` (" +
                    "`id`, `name`, `type`, `icon_background_color`, `icon_name`, `amount`, " +
                    "`credit_limit`, `sequence`, `created_on`, `updated_on`" +
                    ") VALUES (" +
                    "'acc-1', 'Wave', 2, '#000000', 'ic_wallet', 27744.0, " +
                    "0.0, 0, 1710000000000, 1710000000000)",
            )
            execSQL(
                "INSERT INTO `savings_goal` (" +
                    "`id`, `account_id`, `name`, `target_amount`, `target_date`, `notes`, " +
                    "`is_achieved`, `created_on`, `updated_on`, `savings_strategy`, " +
                    "`target_percentage`, `estimated_completion_date`" +
                    ") VALUES (" +
                    "'goal-1', 'acc-1', 'Vacances', 2000.0, NULL, '', " +
                    "0, 1710000000000, 1710000000000, 0, NULL, NULL)",
            )
            close()
        }
    }
}
